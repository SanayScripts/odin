import type { Claim, Source, ClaimResult, Verdict } from "@/lib/types";

const VERDICT_LABEL: Record<Verdict, string> = {
  supported: "✓ Supported",
  contested: "✗ Contested",
  insufficient: "? Insufficient Evidence",
};

export function generateMarkdownReport({
  input,
  claims,
  sources,
  results,
  overall,
  overallConfidence,
}: {
  input: string;
  claims: Claim[];
  sources: Source[];
  results: ClaimResult[];
  overall: Verdict;
  overallConfidence: number;
}): string {
  const now = new Date().toISOString().slice(0, 10);
  const resultMap = Object.fromEntries(results.map((r) => [r.claimId, r]));
  const sourcesByClaimId = sources.reduce<Record<string, Source[]>>((acc, s) => {
    (acc[s.claimId] ??= []).push(s);
    return acc;
  }, {});

  const lines: string[] = [
    `# Odin OSINT Report`,
    `**Date:** ${now}`,
    `**Input:** ${input}`,
    ``,
    `## Overall Verdict: ${VERDICT_LABEL[overall]} (${Math.round(overallConfidence * 100)}% confidence)`,
    ``,
    `---`,
    ``,
  ];

  for (let i = 0; i < claims.length; i++) {
    const c = claims[i];
    const r = resultMap[c.id];
    lines.push(`## C${i + 1}: ${c.text}`);
    if (r) {
      lines.push(`**Verdict:** ${VERDICT_LABEL[r.verdict]} | Confidence: ${Math.round(r.confidence * 100)}% | Independent chains: ${r.independentChains}`);
      lines.push(`Support score: ${r.support.toFixed(2)} | Conflict score: ${r.conflict.toFixed(2)}`);
    }
    lines.push(``);

    const claimSources = sourcesByClaimId[c.id] ?? [];
    const groups: Array<{ label: string; filter: (s: Source) => boolean }> = [
      { label: "Supporting", filter: (s) => s.stance === "supports" },
      { label: "Conflicting", filter: (s) => s.stance === "conflicts" },
      { label: "Neutral", filter: (s) => s.stance === "neutral" || !s.stance },
    ];

    for (const { label, filter } of groups) {
      const group = claimSources.filter(filter);
      if (group.length === 0) continue;
      lines.push(`### ${label}`);
      for (const s of group) {
        const tags = [
          s.tier ? `T${s.tier}` : null,
          s.isOriginal ? "Original" : s.citesSourceId ? "Secondary" : null,
          s.geoMismatch ? "Geo mismatch" : null,
          s.stanceConfidence != null ? `${Math.round(s.stanceConfidence * 100)}% conf` : null,
        ].filter(Boolean).join(", ");
        lines.push(`- **[${s.title}](${s.url})** — ${s.outlet}${s.publishDate ? ` (${s.publishDate})` : ""}${tags ? ` [${tags}]` : ""}`);
        if (s.snippet) lines.push(`  > ${s.snippet.slice(0, 200)}`);
      }
      lines.push(``);
    }
    lines.push(`---`, ``);
  }

  lines.push(`*Generated by Odin — automated OSINT analysis. Verify independently.*`);
  return lines.join("\n");
}
